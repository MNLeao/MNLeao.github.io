/* COMANDOS DE LISTA DE EM JAVASCRIPT
 
lista = []:     Guarda os itens dentro de uma variável.
lista[1]:       Pega o item que está na posição citada.
lista.indexOf('item'):      Revela a posição do item citado.
lista.length:       Mostra o número de elementos presentes na lista.
lista.push('item'):         Adiciona um item no final da lista.
lista.unshift('item'):       Adiciona um item no começo da lista.
lista.pop():        Remove o último item da lista.
lista.shift():      Remove o primeiro item da lista.
lista.splice(1,1):      Corta elemento(s) da lista.
lista.includes('item'):     Verifica se tal item está presente na lista.   
lista.join():       Determina a forma como os items vão ser espaçados/separados.
lista.sort():       Organiza a lista em ordem alfabética.
lista.reverse():        Reverte a ordem da lista que foi definida anteriormente.
*/